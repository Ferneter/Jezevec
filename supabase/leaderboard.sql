create table if not exists public.jezevec_scores (
  id bigint generated by default as identity primary key,
  nickname text not null,
  score integer not null,
  created_at timestamptz not null default now(),
  constraint jezevec_scores_nickname_length
    check (char_length(btrim(nickname)) between 1 and 16),
  constraint jezevec_scores_score_range
    check (score between 0 and 99999)
);

alter table public.jezevec_scores enable row level security;

grant usage on schema public to anon;
revoke all on public.jezevec_scores from anon, authenticated;
grant select on public.jezevec_scores to anon;
revoke all on sequence public.jezevec_scores_id_seq from anon, authenticated;

-- Keep the best existing result for each nickname, ignoring letter case.
with ranked_scores as (
  select
    id,
    row_number() over (
      partition by lower(btrim(nickname))
      order by score desc, created_at asc, id asc
    ) as rn
  from public.jezevec_scores
)
delete from public.jezevec_scores as scores
using ranked_scores
where scores.id = ranked_scores.id
  and ranked_scores.rn > 1;

create unique index if not exists jezevec_scores_nickname_key
  on public.jezevec_scores ((lower(btrim(nickname))));

drop policy if exists "Anyone can read Jezevec scores" on public.jezevec_scores;
create policy "Anyone can read Jezevec scores"
  on public.jezevec_scores for select to anon
  using (true);

drop policy if exists "Anyone can submit a Jezevec score" on public.jezevec_scores;

create or replace function public.submit_jezevec_score(
  p_nickname text,
  p_score integer
)
returns boolean
language plpgsql
security definer
set search_path = pg_catalog, public, pg_temp
as $$
declare
  normalized_nickname text;
  affected_rows integer;
begin
  normalized_nickname := btrim(regexp_replace(coalesce(p_nickname, ''), '[[:space:]]+', ' ', 'g'));
  if char_length(normalized_nickname) not between 1 and 16 then
    raise exception 'Nickname must contain between 1 and 16 characters';
  end if;
  if p_score is null or p_score not between 0 and 99999 then
    raise exception 'Score is outside the allowed range';
  end if;

  insert into public.jezevec_scores as existing (nickname, score)
  values (normalized_nickname, p_score)
  on conflict ((lower(btrim(nickname)))) do update
    set nickname = excluded.nickname,
        score = excluded.score,
        created_at = now()
    where excluded.score > existing.score;

  get diagnostics affected_rows = row_count;
  return affected_rows > 0;
end;
$$;

revoke all on function public.submit_jezevec_score(text, integer) from public, anon, authenticated;
grant execute on function public.submit_jezevec_score(text, integer) to anon;
